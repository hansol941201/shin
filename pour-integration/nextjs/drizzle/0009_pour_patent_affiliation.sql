-- 0009_pour_patent_affiliation.sql
-- 특허 마스터에 "소속" 열 하나 (순방향)
--
-- 0008_pour_patent_master.sql 다음에 실행합니다.
--
-- 왜 나누는가
--   DO 공법과 CNC 는 자사 계열이지만 POUR 공법 자체는 아닙니다.
--   그래서 한 칸에 몰아 담지 않고 두 칸으로 나눕니다.
--
--     affiliation_type  자사계열 / 타사 / 미분류      (이번에 더하는 열)
--     patent_type       POUR / DO / CNC / 타사공법 / 미분류  (0008 의 열을 그대로 씀)
--
--   이렇게 해야 POUR·DO·CNC 를 각각 세면서, 필요할 때 셋을 합쳐
--   "자사계열 전체" 로도 볼 수 있습니다.
--   외부 타사 경쟁사 집계는 affiliation_type = '타사' 만 봅니다.
--   DO·CNC 는 여기에 들어오지 않습니다.
--
-- 옛 값 처리
--   0008 까지는 patent_type 에 '타사' 가 들어갔습니다. 그것은 공법 이름이 아니라
--   소속이었습니다. 이 값을 UPDATE 로 고치지 않고, 읽을 때 옮겨 줍니다.
--     patent_type '타사' → 공법 '타사공법' · 소속 '타사'
--   운영 자료를 건드리지 않기 위해서입니다. 새로 저장되는 건부터 두 칸이 채워집니다.
--
-- 원칙
--   · 열만 더합니다. 기존 열·행을 지우거나 바꾸지 않습니다
--   · UPDATE / DELETE / DROP / TRUNCATE / 표 교체를 쓰지 않습니다
--   · 업체명·공법명을 임의로 채우지 않습니다
-- ============================================================================

ALTER TABLE pour_patents ADD COLUMN affiliation_type TEXT;
